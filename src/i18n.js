// ─── Context & hook ───────────────────────────────────────────────────────────

export const LangContext = React.createContext('it')

export function LangProvider({ lang, children }) {
  return React.createElement(LangContext.Provider, { value: lang || 'it' }, children)
}

export function useLang() {
  const lang = React.useContext(LangContext)
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.it
  const fallback = TRANSLATIONS.it

  const t = (key) => dict[key] ?? fallback[key] ?? key

  const tData = (key) => {
    const entry = DATA_TRANSLATIONS[key]
    if (!entry) return null
    return entry[lang] || entry.it || null
  }

  return { lang, t, tData }
}
